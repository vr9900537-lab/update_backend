from typing import Any, Protocol

from app.schemas.tracking import LocationIngest


class DeviceAdapter(Protocol):
    def parse_location(self, message: dict[str, Any]) -> LocationIngest: ...

    def parse_heartbeat(self, message: dict[str, Any]) -> dict[str, Any]: ...

    def parse_battery(self, message: dict[str, Any]) -> dict[str, Any]: ...

    def parse_sos(self, message: dict[str, Any]) -> dict[str, Any]: ...

    def parse_tamper(self, message: dict[str, Any]) -> dict[str, Any]: ...

    def parse_acknowledgement(self, message: dict[str, Any]) -> dict[str, Any]: ...
